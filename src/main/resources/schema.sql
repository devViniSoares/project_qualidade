CREATE TABLE IF NOT EXISTS usuarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(100) NOT NULL, email VARCHAR(160) NOT NULL UNIQUE,
 senha VARCHAR(100) NOT NULL, perfil VARCHAR(15) NOT NULL CHECK (perfil IN ('ADMIN','GESTOR','USUARIO'))
);
CREATE TABLE IF NOT EXISTS recursos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(100) NOT NULL, tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('SALA','EQUIPAMENTO')),
 localizacao VARCHAR(160) NOT NULL, capacidade INT NOT NULL CHECK (capacidade > 0),
 descricao VARCHAR(500) NOT NULL, ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS reservas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recurso_id BIGINT NOT NULL REFERENCES recursos(id), usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
 inicio TIMESTAMP WITH TIME ZONE NOT NULL, fim TIMESTAMP WITH TIME ZONE NOT NULL,
 finalidade VARCHAR(300) NOT NULL, status VARCHAR(15) NOT NULL CHECK (status IN ('ATIVA','CANCELADA')),
 criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT intervalo_valido CHECK (fim > inicio)
);
CREATE INDEX IF NOT EXISTS idx_reservas_intervalo ON reservas(recurso_id, status, inicio, fim);
CREATE INDEX IF NOT EXISTS idx_reservas_usuario ON reservas(usuario_id);
